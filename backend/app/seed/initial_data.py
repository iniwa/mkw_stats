# Map-point coordinate fields are user-managed calibration after a point is first
# inserted: they are committed via PATCH /api/v1/map-points/{id} and shared by every
# client of the same backend. Seed values for these fields are defaults for NEW rows
# only; a re-seed must never overwrite calibration on an existing map point.
# See docs/decisions/2026-06-19-preserve-map-point-calibration-during-seed.md
MAP_POINT_CALIBRATION_FIELDS = ("x", "y", "radius")


def _sync_seed_fields(existing, values: dict, *, exclude: tuple[str, ...] = ()) -> None:
    for key, value in values.items():
        if key in exclude:
            continue
        setattr(existing, key, value)


def seed(session) -> None:
    # Courses
    for c_data in COURSES:
        existing = session.get(Course, c_data["id"])
        if existing is None:
            session.add(Course(**c_data))
        else:
            _sync_seed_fields(existing, c_data)

    session.flush()

    # Map points
    for mp_data in MAP_POINTS:
        existing = session.get(MapPoint, mp_data["id"])
        if existing is None:
            # Fresh row: seed all fields, including the initial coordinates.
            session.add(MapPoint(**mp_data))
        else:
            # Existing row: refresh seed-owned master fields (course_id, labels)
            # but preserve user-calibrated coordinates.
            _sync_seed_fields(existing, mp_data, exclude=MAP_POINT_CALIBRATION_FIELDS)

    session.flush()

    # Routes
    for r_data in ROUTES:
        existing = session.get(Route, r_data["id"])
        if existing is None:
            session.add(Route(**r_data))
        else:
            _sync_seed_fields(existing, r_data)

    session.flush()

    # VR accounts — insert only if the seed name is absent. The seed account is a
    # default for empty installs, not an authority over the user's active selection:
    # if an active account already exists, add the missing seed account as inactive
    # so we never violate uq_vr_accounts_single_active or displace the user's choice.
    # An existing seed account is left exactly as-is (no field sync).
    for va_data in VR_ACCOUNTS:
        stmt = select(VrAccount).where(VrAccount.name == va_data["name"])
        existing = session.scalars(stmt).first()
        if existing is not None:
            continue
        active_exists = (
            session.scalars(select(VrAccount.id).where(VrAccount.is_active.is_(True))).first()
            is not None
        )
        values = dict(va_data)
        if active_exists:
            values["is_active"] = False
        session.add(VrAccount(id=uuid.uuid4(), **values))
        session.flush()

    session.commit()
    print("Seed complete.")


if __name__ == "__main__":
    with SessionLocal() as session:
        seed(session)
